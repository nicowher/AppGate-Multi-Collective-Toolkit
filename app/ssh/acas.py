"""SSH overlays for ACAS scan prep (unharden) and restore (harden).

Why not Controller API: a PUT would make flush/NOPASSWD/banner the new
desired state. ``/etc/sudoers`` is marked autogenerated by cz-configd, so
visudo-only edits get wiped. We set ``cz-config users/0/nopasswd`` and write
``#includedir`` drop-in ``ACAS_SUDOERS_DROPIN``.

Unharden (SSH, FQDN first):
  1. drop-in + cz-config nopasswd true; rewrite /etc/sudoers to **one**
     ACAS NOPASSWD block (re-runs do not append duplicates)
  2. wrap ``ACAS_BANNER_FILE`` (ssh_confirm.sh) with ``if [ -t 0 ]``
   3. mkdir ``ACAS_SCAP_HOME`` (/home/svc-acas) for SCAP. Harden removes it.
  4. iptables/ip6tables -F SSHBRUTE; -A ACCEPT **last**
     (cz-config set can rebuild the firewall if we flush first)

Harden:
  1. cz-config nopasswd false. A failure exits. It is not masked.
  2. restore banner / sudoers ``*.pre-acas``. A rewrite is mode 440.
     ``visudo`` failure exits. It does not report success.
  3. rm drop-in and ``ACAS_SCAP_HOME`` (unharden still creates that directory)
  4. restore the saved SSHBRUTE chain. A missing rules file deletes the
     unharden ACCEPT and fails. Harden does not report success with that rule left in.
  5. ``nohup systemctl restart cz-configd`` (foreground restart drops SSH)
"""
import re
import shlex
import sys
from typing import Sequence, Union

from config import (
    ACAS_BANNER_FILE,
    ACAS_BANNER_TTY_GUARD,
    ACAS_CZCONFIGD_UNIT,
    ACAS_IPTABLES_BINS,
    ACAS_IPTABLES_CHAIN,
    ACAS_SCAP_HOME,
    ACAS_SSH_TIMEOUT,
    ACAS_SUDOERS_DROPIN,
    ACAS_SUDOERS_FILE,
    ACAS_SUDOERS_MARK_BEGIN,
    ACAS_SUDOERS_MARK_END,
    DEBUG,
    SSH_LOG_PREVIEW,
)

from .client import SSHSession

USER_RE = re.compile(r"^[A-Za-z0-9_.-]+$")


def _quote_words(values: Sequence[str]) -> str:
    return " ".join(shlex.quote(v) for v in values if v)


class AcasPrep(SSHSession):
    """FQDN-first SSH for ACAS unharden / harden."""

    def unharden(self, host: Union[str, Sequence[str]]) -> str:
        # print(f"DEBUG acas: unharden hosts={host!r}")
        return self._run_script(host, self._unharden_script())

    def harden(self, host: Union[str, Sequence[str]]) -> str:
        """A background restart can fail after the script exits. Recheck on a new session."""
        # print(f"DEBUG acas: harden hosts={host!r}")
        text = self._run_script(host, self._harden_script())
        unit = shlex.quote(ACAS_CZCONFIGD_UNIT)
        status = self._with_ssh_endpoints(
            host,
            lambda c: self._sudo(c, f"systemctl is-active {unit}", check=False),
            error="could not recheck cz-configd",
        )
        if (status or "").strip() != "active":
            raise ValueError(
                f"cz-configd is not active after harden: {(status or '').strip()!r}"
            )
        return text

    def _unharden_script(self) -> str:
        """Later steps can fail after sudoers is replaced. The exit trap restores that file. Rules go under /run so a local user cannot swap the file."""
        user = (self.ssh_user or "").strip()
        if not USER_RE.fullmatch(user):
            raise ValueError(f"Unsafe SSH username for sudoers: {user!r}")
        bins = _quote_words(ACAS_IPTABLES_BINS)
        chain = shlex.quote(ACAS_IPTABLES_CHAIN)
        drop = shlex.quote(ACAS_SUDOERS_DROPIN)
        sudoers = shlex.quote(ACAS_SUDOERS_FILE)
        mark_b = shlex.quote(ACAS_SUDOERS_MARK_BEGIN)
        mark_e = shlex.quote(ACAS_SUDOERS_MARK_END)
        user_q = shlex.quote(f"{user} ALL=(ALL) NOPASSWD: ALL")
        banner = shlex.quote(ACAS_BANNER_FILE)
        guard = ACAS_BANNER_TTY_GUARD
        scap = shlex.quote(ACAS_SCAP_HOME)
        return f"""
set -e
sudoers_committed=0
rollback_sudoers() {{
  [ "$sudoers_committed" = 1 ] || return 0
  if [ -f "${{SUDOERS}}.pre-acas" ]; then
    cp -a "${{SUDOERS}}.pre-acas" "$SUDOERS" || true
    chmod 440 "$SUDOERS" || true
  fi
  rm -f "$DROP" || true
}}
trap rollback_sudoers EXIT
echo STEP_SUDOERS_START
DROP={drop}
SUDOERS={sudoers}
printf '%s\\n' {user_q} > "$DROP"
chmod 440 "$DROP"
if visudo -cf "$DROP" >/dev/null 2>&1; then
  echo STEP_SUDOERS_DROPIN_OK
else
  rm -f "$DROP"
  echo STEP_SUDOERS_FAIL drop-in
  exit 1
fi
if command -v cz-config >/dev/null 2>&1; then
  if cz-config set -j users/0/nopasswd true; then
    echo STEP_CZCONFIG_NOPASSWD_TRUE
  else
    echo STEP_CZCONFIG_NOPASSWD_FAIL
  fi
fi
[ -f "${{SUDOERS}}.pre-acas" ] || cp -a "$SUDOERS" "${{SUDOERS}}.pre-acas"
tmp="${{SUDOERS}}.acas.$$"
awk -v b={mark_b} -v e={mark_e} -v line={user_q} '
  $0 == b {{ skip=1; next }}
  $0 == e {{ skip=0; next }}
  skip {{ next }}
  $0 == line {{ next }}
  {{ print }}
' "$SUDOERS" > "$tmp"
printf '\\n%s\\n%s\\n%s\\n' {mark_b} {user_q} {mark_e} >> "$tmp"
if visudo -cf "$tmp" >/dev/null 2>&1; then
  mv "$tmp" "$SUDOERS"
  chmod 440 "$SUDOERS"
  sudoers_committed=1
  echo STEP_SUDOERS_OK
else
  rm -f "$tmp"
  echo STEP_SUDOERS_FAIL visudo
  exit 1
fi

echo STEP_SCAP_DIR
mkdir -p {scap}
chmod 755 {scap} 2>/dev/null || true
echo STEP_SCAP_DIR_OK {scap}

echo STEP_BANNER_START
f={banner}
if [ ! -f "$f" ]; then
  echo STEP_BANNER_SKIP missing "$f"
else
if grep -q -- '-t 0' "$f"; then
  echo "STEP_BANNER_ALREADY $f"
else
  [ -f "${{f}}.pre-acas" ] || cp -a "$f" "${{f}}.pre-acas"
  tmp="${{f}}.acas.$$"
  awk '
    {{ print }}
    !ins && /SSH_CLIENT/ {{ print "{guard}"; ins=1 }}
    ins && !closed && /^done[[:space:]]*$/ {{ print "fi"; closed=1 }}
  ' "$f" > "$tmp"
  if bash -n "$tmp" 2>/dev/null; then
    mv "$tmp" "$f"
    echo "STEP_BANNER_OK $f"
  else
    rm -f "$tmp"
    echo STEP_BANNER_SKIP bash -n "$f"
  fi
fi
fi

echo STEP_IPTABLES_START
for bin in {bins}; do
  if "$bin" -w -n -L {chain} >/dev/null 2>&1; then
    ruledir=/run/mct-sshbrute
    if [ -L "$ruledir" ]; then
      echo STEP_IPTABLES_FAIL symlink
      exit 1
    fi
    mkdir -p "$ruledir"
    chmod 700 "$ruledir"
    if [ -L "$ruledir" ]; then
      echo STEP_IPTABLES_FAIL symlink
      exit 1
    fi
    tmp=$(mktemp "$ruledir/${{bin}}.XXXXXX") || exit 1
    "$bin" -S {chain} > "$tmp" || {{ rm -f "$tmp"; exit 1; }}
    chmod 600 "$tmp" || true
    rules="$ruledir/${{bin}}.rules"
    if [ -L "$rules" ]; then
      rm -f "$tmp"
      echo STEP_IPTABLES_FAIL symlink
      exit 1
    fi
    mv -f "$tmp" "$rules"
    "$bin" -w -F {chain}
    "$bin" -w -A {chain} -j ACCEPT
    echo STEP_IPTABLES_OK "$bin"
    "$bin" -w -S {chain} || true
  else
    echo STEP_IPTABLES_SKIP "$bin" no {chain} chain
  fi
done
sudoers_committed=0
trap - EXIT
echo STEP_UNHARDEN_DONE
"""

    def _harden_script(self) -> str:
        """The drop-in is removed before any exit. Compare the saved rules before deleting the file, or the check fails and later steps never run."""
        user = (self.ssh_user or "").strip() or "cz"
        drop = shlex.quote(ACAS_SUDOERS_DROPIN)
        banner = shlex.quote(ACAS_BANNER_FILE)
        sudoers = shlex.quote(ACAS_SUDOERS_FILE)
        unit = shlex.quote(ACAS_CZCONFIGD_UNIT)
        mark_b = shlex.quote(ACAS_SUDOERS_MARK_BEGIN)
        mark_e = shlex.quote(ACAS_SUDOERS_MARK_END)
        user_q = shlex.quote(f"{user} ALL=(ALL) NOPASSWD: ALL")
        chain = shlex.quote(ACAS_IPTABLES_CHAIN)
        scap = shlex.quote(ACAS_SCAP_HOME)
        return f"""
echo STEP_SUDOERS_REMOVE
rm -f {drop}
if command -v cz-config >/dev/null 2>&1; then
  if cz-config set -j users/0/nopasswd false; then
    echo STEP_CZCONFIG_NOPASSWD_FALSE
  else
    echo STEP_CZCONFIG_NOPASSWD_FAIL
    exit 1
  fi
fi
echo STEP_IPTABLES_RESTORE
for bin in iptables ip6tables; do
  ruledir=/run/mct-sshbrute
  rules="$ruledir/${{bin}}.rules"
  chain={chain}
  if [ -L "$ruledir" ] || [ -L "$rules" ] || [ ! -f "$rules" ]; then
    "$bin" -D "$chain" -j ACCEPT 2>/dev/null || true
    echo STEP_IPTABLES_RESTORE_FAIL "$bin" missing-rules
    exit 1
  fi
  "$bin" -F "$chain" || exit 1
  set -f
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      -A*)
        read -r -a args <<< "$line"
        "$bin" -w "${{args[@]}}" || exit 1
        ;;
    esac
  done < "$rules"
  set +f
  saved=$(grep '^-A' "$rules" | sort)
  live=$("$bin" -S "$chain" | grep '^-A' | sort)
  if [ "$saved" != "$live" ]; then
    echo STEP_IPTABLES_RESTORE_FAIL "$bin"
    exit 1
  fi
  rm -f "$rules"
  echo STEP_IPTABLES_RESTORED "$bin"
done
echo STEP_BANNER_RESTORE
f={banner}
if [ -f "${{f}}.pre-acas" ]; then
  mv "${{f}}.pre-acas" "$f"
  echo "STEP_BANNER_RESTORED $f"
fi
SUDOERS={sudoers}
if [ -f "${{SUDOERS}}.pre-acas" ]; then
  mv "${{SUDOERS}}.pre-acas" "$SUDOERS"
  chmod 440 "$SUDOERS"
  echo STEP_SUDOERS_RESTORED
else
  tmp="${{SUDOERS}}.acas.$$"
  awk -v b={mark_b} -v e={mark_e} -v line={user_q} '
    $0 == b {{ skip=1; next }}
    $0 == e {{ skip=0; next }}
    skip {{ next }}
    $0 == line {{ next }}
    {{ print }}
  ' "$SUDOERS" > "$tmp"
  if visudo -cf "$tmp" >/dev/null 2>&1; then
    mv "$tmp" "$SUDOERS"
    chmod 440 "$SUDOERS"
    echo STEP_SUDOERS_OK
  else
    rm -f "$tmp"
    echo STEP_SUDOERS_FAIL visudo
    exit 1
  fi
fi
echo STEP_SCAP_DIR_REMOVE
rm -rf {scap} || {{ echo STEP_SCAP_DIR_REMOVE_FAIL; exit 1; }}
echo STEP_CZCONFIGD_RESTART
nohup systemctl restart {unit} >/dev/null 2>&1 &
echo STEP_HARDEN_DONE
"""

    def _run_script(self, host: Union[str, Sequence[str]], script: str) -> str:
        if DEBUG:
            print(
                f"      DEBUG acas: script_len={len(script)} timeout={ACAS_SSH_TIMEOUT}",
                file=sys.stderr,
            )
        result = self._with_ssh_endpoints(
            host,
            lambda c, s=script: self._sudo_script(c, s, timeout=ACAS_SSH_TIMEOUT),
            error="SSH failed",
        )
        rc, text = result
        # print(f"DEBUG acas: rc={rc} steps={[ln for ln in text.splitlines() if ln.startswith('STEP_')]}")
        done = "STEP_HARDEN_DONE" in text or "STEP_UNHARDEN_DONE" in text
        if done and rc == 0:
            return text
        if rc != 0 or "STEP_SUDOERS_FAIL" in text or not done:
            steps = " ".join(ln for ln in text.splitlines() if ln.startswith("STEP_"))
            raise ValueError(
                f"ACAS script failed (exit {rc}): {(steps or text.strip())[:SSH_LOG_PREVIEW]}"
            )
        return text
